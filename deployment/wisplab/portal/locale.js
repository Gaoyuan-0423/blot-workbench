export function resolveLanguage(search, saved) {
  const requested = new URLSearchParams(search).get("lang");
  return requested === "zh" || requested === "en"
    ? requested
    : saved === "en"
      ? "en"
      : "zh";
}

export function languageUrl(href, language, base) {
  const url = new URL(href, base);
  url.searchParams.set("lang", language === "en" ? "en" : "zh");
  return url.href;
}

function initialize() {
  let saved;
  try {
    saved = localStorage.getItem(STORAGE_KEY);
  } catch {
    /* URL retains the choice when storage is unavailable. */
  }
  let language = resolveLanguage(location.search, saved);

  function render(next, updateUrl = false) {
    language = next === "en" ? "en" : "zh";
    document.documentElement.lang = language === "en" ? "en" : "zh-CN";
    for (const [attribute, target] of [
      ["data-i18n", null],
      ["data-i18n-aria-label", "aria-label"],
      ["data-i18n-content", "content"],
    ]) {
      for (const node of document.querySelectorAll(`[${attribute}]`)) {
        const key = node.getAttribute(attribute);
        const value = messages[key]?.[language];
        if (value === undefined)
          throw new Error(`Missing portal translation: ${key}`);
        if (target) node.setAttribute(target, value);
        else node.textContent = value;
      }
    }
    for (const link of document.querySelectorAll("a[data-language-link]")) {
      link.href = languageUrl(
        link.getAttribute("href"),
        language,
        location.href,
      );
    }
    for (const button of document.querySelectorAll("[data-language]")) {
      button.setAttribute(
        "aria-pressed",
        String(button.dataset.language === language),
      );
    }
    try {
      localStorage.setItem(STORAGE_KEY, language);
    } catch {
      /* Optional browser storage. */
    }
    if (updateUrl)
      history.replaceState(
        history.state,
        "",
        languageUrl(location.href, language, location.href),
      );
  }

  for (const button of document.querySelectorAll("[data-language]")) {
    button.addEventListener("click", () =>
      render(button.dataset.language, true),
    );
  }
  window.addEventListener("popstate", () =>
    render(resolveLanguage(location.search, language)),
  );
  window.addEventListener("storage", (event) => {
    if (
      event.key === STORAGE_KEY &&
      (event.newValue === "zh" || event.newValue === "en")
    )
      render(event.newValue, true);
  });
  render(language);
}

if (typeof document !== "undefined") initialize();
